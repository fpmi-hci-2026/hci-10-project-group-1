def color_table(pal: str, mode: str) -> list[str]:
    v = T["palettes"][pal][mode]
    L = ["| Токен | Значение | Назначение |", "|---|---|---|"]
    for k, hexv in v.items():
        L.append(f"| `{k}` | `{hexv}` | {ROLE.get(k, '')} |")
    return L


def type_table() -> list[str]:
    L = ["| Ступень | Размер | Интерлиньяж | Начертание | Трекинг |", "|---|---|---|---|---|"]
    for k, s in T["typography"]["scale"].items():
        note = f" — {s['note']}" if "note" in s else ""
        L.append(f"| `{k}`{note} | {s['size']} px | {s['line']} px | {s['weight']} | {s['tracking']} |")
    return L


def status_table(pal: str, mode: str) -> list[str]:
    v = T["palettes"][pal][mode]
    L = ["| Статус (ENUM) | Подпись | Фон | Текст | В каком контуре |", "|---|---|---|---|---|"]
    for sid, s in T["status"].items():
        if sid.startswith("$"):
            continue
        L.append(f"| `{sid}` | {s['label']} | `{v[s['bg']]}` | `{v[s['fg']]}` | {s['contour']} |")
    return L


def grid_table() -> list[str]:
    L = ["| Диапазон | Артборд | Контейнер | Колонок | Гаттер | Колонка | Поля | Карточек | Фильтры |",
         "|---|---|---|---|---|---|---|---|---|"]
    for b in T["grid"]["breakpoints"]:
        L.append(f"| {b['range']} | {b['artboard']} | {b['container']} | {b['columns']} | "
                 f"{b['gutter']} | {b['column']} | {b['margin']} | {b['cards']} | {b['filters']} |")
    return L


